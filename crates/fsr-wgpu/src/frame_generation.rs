unsafe extern "system" fn vk_queue_present(
    queue: vk::Queue,
    present_info: *const vk::PresentInfoKHR<'_>,
) -> vk::Result {
    // SAFETY: wgpu-hal presents exactly one swapchain per call.
    let swapchain = unsafe {
        let info = &*present_info;
        if info.swapchain_count == 0 {
            vk::SwapchainKHR::null()
        } else {
            *info.p_swapchains
        }
    };
    let (route, real) = {
        let guard = presentation();
        let Some(vulkan) = guard.as_ref().and_then(|s| s.vulkan.as_ref()) else {
            return vk::Result::ERROR_INITIALIZATION_FAILED;
        };
        (vulkan.routed(swapchain), vulkan.real.queue_present_khr)
    };
    let Some(replacement) = route else {
        // SAFETY: forwarding wgpu-hal's arguments.
        return unsafe { real(queue, present_info) };
    };
    // SAFETY: the provider's replacement for vkQueuePresentKHR on its swapchain.
    let result = unsafe { (replacement.present)(queue, present_info) };
    // SAFETY: `swapchain` is the provider's live swapchain.
    count_present_total(unsafe { (replacement.last_present_count)(swapchain) });
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    fn family(flags: vk::QueueFlags, count: u32, present: bool) -> QueueFamily {
        QueueFamily {
            flags,
            count,
            present,
        }
    }

    const G: vk::QueueFlags = vk::QueueFlags::from_raw(0b111); // graphics | compute | transfer
    const C: vk::QueueFlags = vk::QueueFlags::from_raw(0b110); // compute | transfer
    const T: vk::QueueFlags = vk::QueueFlags::TRANSFER;

    #[test]
    fn amd_style_families_give_four_distinct_queues() {
        let families = [family(G, 1, true), family(C, 4, true), family(T, 2, false)];
        let plan = plan_vulkan_queues(&families, WGPU_GAME_QUEUE).expect("plan");
        assert_eq!(
            plan.present,
            QueueSlot {
                family: 1,
                index: 0
            }
        );
        assert_eq!(
            plan.async_compute,
            QueueSlot {
                family: 1,
                index: 1
            }
        );
        assert_eq!(
            plan.image_acquire,
            QueueSlot {
                family: 2,
                index: 0
            }
        );
        assert_eq!(plan.queue_counts(WGPU_GAME_QUEUE, 3), [1, 2, 1]);
    }

    #[test]
    fn spare_graphics_queues_keep_presents_in_the_game_family() {
        // RX 9070 XT (Vulkan, Windows): 8 graphics, 8 compute, 1 transfer queue.
        let families = [family(G, 8, true), family(C, 8, true), family(T, 1, false)];
        let plan = plan_vulkan_queues(&families, WGPU_GAME_QUEUE).expect("plan");
        let slot = |family, index| QueueSlot { family, index };
        assert_eq!(plan.present, slot(0, 1));
        assert_eq!(plan.async_compute, slot(1, 0));
        assert_eq!(plan.image_acquire, slot(2, 0));
        assert_eq!(plan.queue_counts(WGPU_GAME_QUEUE, 3), [2, 1, 1]);
    }

    #[test]
    fn a_single_graphics_queue_cannot_host_frame_generation() {
        assert_eq!(
            plan_vulkan_queues(&[family(G, 1, true)], WGPU_GAME_QUEUE),
            None
        );
    }

    #[test]
    fn a_wide_graphics_family_shares_the_game_family() {
        let plan = plan_vulkan_queues(&[family(G, 16, true)], WGPU_GAME_QUEUE).expect("plan");
        assert_eq!(
            plan.present,
            QueueSlot {
                family: 0,
                index: 1
            }
        );
        assert_eq!(
            plan.async_compute,
            QueueSlot {
                family: 0,
                index: 2
            }
        );
        assert_eq!(
            plan.image_acquire,
            QueueSlot {
                family: 0,
                index: 3
            }
        );
        assert_eq!(plan.queue_counts(WGPU_GAME_QUEUE, 1), [4]);
    }
}
